-- Smart Finance Manager: PostgreSQL schema
-- Run inside the smart_finance database. Safe to re-run (IF NOT EXISTS).
--   psql -U postgres -d smart_finance -f database/schema.sql
-- Note: the Spring Boot app also creates these tables automatically on startup
-- (spring.jpa.hibernate.ddl-auto=update), so this script is optional.

CREATE TABLE IF NOT EXISTS users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255) NOT NULL,
    email     VARCHAR(255) NOT NULL UNIQUE,
    password  VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS transactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description  VARCHAR(255)   NOT NULL,
    amount       NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    category     VARCHAR(255)   NOT NULL,
    type         VARCHAR(255)   NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
    date         DATE           NOT NULL,
    user_id      BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS budgets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category      VARCHAR(255)   NOT NULL,
    limit_amount  NUMERIC(12, 2) NOT NULL CHECK (limit_amount > 0),
    user_id       BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_budgets_user_category UNIQUE (user_id, category)
);

CREATE TABLE IF NOT EXISTS savings_goals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255)   NOT NULL,
    target_amount  NUMERIC(12, 2) NOT NULL CHECK (target_amount > 0),
    saved_amount   NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (saved_amount >= 0),
    user_id        BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_transactions_user ON transactions (user_id);
CREATE INDEX IF NOT EXISTS idx_savings_goals_user ON savings_goals (user_id);
